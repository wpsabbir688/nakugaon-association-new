import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { env } from './config/env.js';
import { errorHandler, ok } from './errors.js';
import { apiLimiter } from './middleware/rateLimit.js';
import authRoutes from './routes/auth.js';
import membersRoutes from './routes/members.js';
import publicRoutes from './routes/public.js';
import vehicleRoutes from './routes/vehicleEntries.js';
import weighbridgeRoutes from './routes/weighbridge.js';
import paymentsRoutes from './routes/payments.js';
import feeRulesRoutes from './routes/feeRules.js';
import expensesRoutes from './routes/expenses.js';
import accountingRoutes from './routes/accounting.js';
import dashboardRoutes from './routes/dashboard.js';
import noticesRoutes from './routes/notices.js';
import settingsRoutes from './routes/settings.js';
import uploadsRoutes from './routes/uploads.js';
export function createApp() {
  const app = express();
  app.disable('x-powered-by');
  app.use(helmet());
  app.use(cors({ origin: (origin, cb) => { if (!origin || env.corsOrigins.includes(origin)) cb(null, true); else cb(null, false); }, credentials: true }));
  app.use(express.json({ limit: '1mb' }));
  app.use(cookieParser());
  app.use('/api/v1', apiLimiter);
  app.get('/health', (req, res) => ok(res, { status: 'ok', service: 'nakugaon-association-server' }));
  app.use('/api/v1/auth', authRoutes);
  app.use('/api/v1/members', membersRoutes);
  app.use('/api/v1/public', publicRoutes);
  app.use('/api/v1/vehicle-entries', vehicleRoutes);
  app.use('/api/v1/weighbridge', weighbridgeRoutes);
  app.use('/api/v1/payments', paymentsRoutes);
  app.use('/api/v1/fee-rules', feeRulesRoutes);
  app.use('/api/v1/expenses', expensesRoutes);
  app.use('/api/v1/accounting', accountingRoutes);
  app.use('/api/v1/dashboard', dashboardRoutes);
  app.use('/api/v1/notices', noticesRoutes);
  app.use('/api/v1/settings', settingsRoutes);
  app.use('/api/v1/uploads', uploadsRoutes);
  app.use((req, res) => res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Route not found' } }));
  app.use(errorHandler);
  return app;
}
